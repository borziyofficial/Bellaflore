export function detectCategory(filePath, defaultCat) {
  const base = filePath.split("/").pop().toLowerCase();
  if (/pion|peoni/.test(base)) return "peonies";
  if (/rose|roza|rozy|kust/.test(base)) return "roses";
  if (/gort|hydr/.test(base)) return "hydrangeas";
  if (/mix|mati|matiol/.test(base)) return "author";
  if (/white/.test(base)) return "mono-bouquets";
  return defaultCat;
}

// ---- Real content-based type detection (fixes: script previously guessed
// MIME purely from the file extension, which mislabeled 4 real HEIC photos
// as image/jpeg). Detects the actual format from magic bytes in the file. ----
export function sniffImageFormat(buf) {
  if (!buf || buf.length < 12) return "unknown";
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpeg";
  if (buf.slice(0, 8).toString("hex") === "89504e470d0a1a0a") return "png";
  if (buf.slice(0, 4).toString("ascii") === "RIFF" && buf.slice(8, 12).toString("ascii") === "WEBP") return "webp";
  if (buf.slice(0, 6).toString("ascii") === "GIF87a" || buf.slice(0, 6).toString("ascii") === "GIF89a") return "gif";
  if (buf.slice(4, 8).toString("ascii") === "ftyp") {
    const brand = buf.slice(8, 12).toString("ascii");
    if (["heic", "heix", "hevc", "hevx", "mif1", "msf1", "heim", "heis", "hevm", "hevs"].includes(brand)) {
      return "heic";
    }
  }
  return "unknown";
}

export function mimeForFormat(fmt) {
  return { jpeg: "image/jpeg", png: "image/png", webp: "image/webp", gif: "image/gif", heic: "image/heic" }[fmt] ?? null;
}
